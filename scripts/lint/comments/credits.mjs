export const NAMES = [
  'codex',
  'fable',
  'claude',
  'astra',
  'chatgpt',
  'openai',
  'anthropic',
  'lifeos',
  'gpt-?[0-9][a-z0-9.]*',
  'gemini',
  'opus',
];

const TOOL_NAMES = ['gpt', 'copilot', 'cursor', 'devin', 'aider'];

const NAMED_EXCEPTIONS = [
  ['scripts/lint/comments/credits.mjs', 'the checker holds the names it looks for'],
  ['.github/no-new-comments-e2e.sh', 'its fixtures hold the patterns on purpose'],
  ['.gitignore', 'ignore rules name tool folders'],
  ['package-lock.json', 'lockfiles list dependency names as published'],
];

const exempt = (path) => NAMED_EXCEPTIONS.some(([file]) => file === path);

const wordPattern = (word) => new RegExp(`(^|[^a-z0-9_])${word}([^a-z0-9_]|$)`);
const names = NAMES.map((word) => ({ word, pattern: wordPattern(word) }));
const toolNames = TOOL_NAMES.map((word) => ({ word, pattern: wordPattern(word) }));

const named = (text) => names.filter((n) => n.pattern.test(text.toLowerCase())).map((n) => n.word);

const anyName = (text) => names.some((n) => n.pattern.test(text)) || toolNames.some((n) => n.pattern.test(text));

function labelled(text) {
  let lower = text.toLowerCase();
  if (/(^|[^a-z0-9_])ai[- ](generated|assisted|authored|written)([^a-z0-9_]|$)/.test(lower)) return true;
  for (let at = lower.search(/generated (with|by)/); at >= 0; at = lower.search(/generated (with|by)/)) {
    const after = lower.slice(at).replace(/^generated (with|by)/, '');
    const window = after.slice(0, 63);
    if (/(^|[^a-z0-9_])(ai|t3)([^a-z0-9_]|$)/.test(window) || anyName(window)) return true;
    lower = after;
  }
  return false;
}

const isBot = (identity) => /\[bot\]|(^|[^a-z0-9])bot@/.test(identity);
const creditsBot = (identity) => isBot(identity.toLowerCase()) || anyName(identity.toLowerCase());

function coauthor(text) {
  const match = /co-authored-by:(.*)$/i.exec(text);
  return Boolean(match) && creditsBot(match[1]);
}

function autogeneratedLines(lines) {
  const hidden = new Set();
  for (let i = 0; i < lines.length; i++) {
    if (!lines[i].includes('<!-- This is an auto-generated comment')) continue;
    const end = lines.findIndex((line, j) => j > i && line.includes('<!-- end of auto-generated comment'));
    if (end < 0) break;
    for (let j = i; j <= end; j++) hidden.add(j);
    i = end;
  }
  return hidden;
}

export function creditProblems({ changes, log, title, body }) {
  const found = [];
  const check = (where, text) => {
    const hits = named(text);
    if (coauthor(text)) found.push([where, 'credits an assistant, model or bot as co-author', text]);
    else if (hits.length) found.push([where, `names an assistant or model (${hits.join(', ')})`, text]);
    else if (labelled(text)) found.push([where, 'carries an authorship label', text]);
  };
  for (const change of changes) {
    if (!change.after || exempt(change.after)) continue;
    for (const [line, text] of change.added) check(`${change.after}:${line}`, text);
  }
  for (const record of log.split('\x1e')) {
    const [sha, author, committer, message] = record.replace(/^\n/, '').split('\x1f');
    if (!sha) continue;
    const commit = `commit ${sha.slice(0, 9)}`;
    if (creditsBot(author)) found.push([commit, 'is authored by an assistant, model or bot', author]);
    if (creditsBot(committer)) found.push([commit, 'is committed by an assistant, model or bot', committer]);
    message
      .replace(/\n+$/, '')
      .split('\n')
      .forEach((text, i) => check(`${commit} line ${i + 1}`, text));
  }
  if (title) check('PR title', title);
  const bodyLines = body.replace(/\r/g, '').split('\n');
  const hidden = autogeneratedLines(bodyLines);
  bodyLines.forEach((text, i) => hidden.has(i) || check(`PR body line ${i + 1}`, text));
  return found;
}
