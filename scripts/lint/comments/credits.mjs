export const NAMES = [
  'claude',
  'chatgpt',
  'openai',
  'anthropic',
  'lifeos',
  'sol-loop',
  'gpt-?[0-9][a-z0-9.]*',
  'swe-?[0-9]+',
];

const MODEL_WORDS = [
  'codex',
  'fable',
  'astra',
  'gemini',
  'opus',
  'sonnet',
  'haiku',
  'sol',
  'gpt',
  'copilot',
  'cursor',
  'devin',
  'aider',
];

const NAMED_EXCEPTIONS = [
  ['scripts/lint/comments/credits.mjs', 'the checker holds the names it looks for'],
  ['.github/no-new-comments-e2e.sh', 'its fixtures hold the patterns on purpose'],
  ['.gitignore', 'ignore rules name tool folders'],
  ['package-lock.json', 'lockfiles list dependency names as published'],
];

const exempt = (path) => NAMED_EXCEPTIONS.some(([file]) => file === path);

const words = (list, tail = '') => new RegExp(`(^|[^a-z0-9_])(${list.join('|')})${tail}(?![a-z0-9_])`, 'g');
const strong = words(NAMES);
const versioned = words(MODEL_WORDS, '[ -]?v?[0-9]+(\\.[0-9]+)*');
const anyWord = words([...NAMES, ...MODEL_WORDS, 'ai', 't3', 'agent']);
const BOT = /\[bot\]|(^|[^a-z0-9])bot@/;
const VERBS = ['generated', 'written', 'made', 'built', 'created', 'authored', 'assisted', 'reviewed', 'helped'];
const CREDIT_VERB = new RegExp(`(${VERBS.join('|')}) (with|by|using|via)`);
const TRAILER = /(co-authored|assisted|helped|generated|reviewed|written)-by:(.*)$/;

const matches = (pattern, text) => [...text.matchAll(pattern)].map((m) => m[0].replace(/^[^a-z0-9]/, ''));

function named(text) {
  const lower = text.toLowerCase();
  return [...new Set([...matches(strong, lower), ...matches(versioned, lower)])];
}

const credits = (text) => BOT.test(text) || matches(anyWord, text).length > 0;

function labelled(text) {
  const lower = text.toLowerCase();
  if (/(^|[^a-z0-9_])ai[- ](generated|assisted|authored|written)([^a-z0-9_]|$)/.test(lower)) return true;
  return lower.split(CREDIT_VERB).some((part, i) => i % 3 === 0 && i > 0 && credits(part.split(/[.;!?]/)[0]));
}

const creditsIdentity = (identity) => {
  const lower = identity.toLowerCase();
  return BOT.test(lower) || named(lower).length > 0 || /(^|[^a-z])(copilot|cursor ?agent)([^a-z]|$)/.test(lower);
};

function autogeneratedLines(lines) {
  const hidden = new Set();
  for (let i = 0; i < lines.length; i++) {
    if (!lines[i].includes('<!-- This is an auto-generated comment')) continue;
    const end = lines.findIndex((line, j) => j > i && line.includes('<!-- end of auto-generated comment'));
    if (end < 0) break;
    for (let j = i; j <= end; j++) hidden.add(j);
    i = end;
  }
  return hidden;
}

export function creditProblems({ changes, log, title, body }) {
  const found = [];
  const check = (where, text) => {
    const trailer = TRAILER.exec(text.toLowerCase());
    const hits = named(text);
    if (trailer && credits(trailer[2])) found.push([where, 'credits an assistant, model or bot as co-author', text]);
    else if (hits.length) found.push([where, `names an assistant or model (${hits.join(', ')})`, text]);
    else if (labelled(text)) found.push([where, 'carries an authorship label', text]);
  };
  for (const change of changes) {
    if (!change.after || exempt(change.after)) continue;
    for (const [line, text] of change.added) check(`${change.after}:${line}`, text);
  }
  for (const record of log.split('\0').filter(Boolean)) {
    const [sha, author, committer, ...message] = record.replace(/^\n/, '').split('\n');
    const commit = `commit ${sha.slice(0, 9)}`;
    if (creditsIdentity(author)) found.push([commit, 'is authored by an assistant, model or bot', author]);
    if (creditsIdentity(committer)) found.push([commit, 'is committed by an assistant, model or bot', committer]);
    message
      .join('\n')
      .replace(/\n+$/, '')
      .split(/[\n\x1e\x1f]/)
      .forEach((text, i) => check(`${commit} line ${i + 1}`, text));
  }
  if (title) check('PR title', title);
  const bodyLines = body.replace(/\r/g, '').split('\n');
  const hidden = autogeneratedLines(bodyLines);
  bodyLines.forEach((text, i) => hidden.has(i) || check(`PR body line ${i + 1}`, text));
  return found;
}
